export const ART_DIRECTION_PRINCIPLES = `
PROFESSIONAL CREATIVE JUDGMENT (apply selectively — not every principle every time)

Visual storytelling:
- One dominant teaching idea. Secondary elements support; they do not compete.
- The glance test: before reading all text, a viewer should sense the hazard or safe action.

Conceptual advertising:
- Prefer a specific, memorable visual idea over generic "safety collage."
- A metaphor is useful only when it clarifies the hazard — never when it obscures it.

Information hierarchy:
- Headline first, teaching visual second, body message third, brand last.
- Do not give equal visual weight to every element.

Editorial composition:
- Intentional asymmetry, crop, and negative space beat centered stock layouts when they serve the lesson.
- Edge-to-edge continuity — no empty reserved logo boxes.

Emotional storytelling:
- Match emotion to the topic: restrained dread for invisible threats; warmth for child safety; urgency without panic for weather; calm authority for crime prevention.
- Never fearmonger or sensationalize.

Intentional contrast:
- Contrast for readability and focus, not decorative glow or HDR gloss.

Visual restraint:
- Remove elements that do not teach. Clutter is not professionalism.

Creative metaphors:
- Optional, not required. Use only when they clarify; never invent a visible form for an invisible hazard (no CO “gas cloud”).

Typography as design:
- Type is part of the composition: scale, weight, placement, and contrast are deliberate.
- Approved text is locked — design around it; do not rewrite it.

Distinctive art direction:
- Choose a treatment that fits THIS topic. Avoid repeating the same centered photo+title formula across unrelated topics.

Audience psychology:
- Residents scroll fast. Make the stakes and the action obvious within a second.

Brand integration:
- Official logo is an identity mark, not decoration. Faithful asset bottom-right when provided.
`

